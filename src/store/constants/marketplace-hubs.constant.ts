export type MarketplaceHubDefinition = {
  id: string;
  name: string;
  latitude: number;
  longitude: number;
  aliases: string[];
};

function slugify(name: string): string {
  return name
    .trim()
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function hub(
  name: string,
  latitude: number,
  longitude: number,
  aliases: string[] = [],
): MarketplaceHubDefinition {
  const id = slugify(name);
  const normalizedAliases = aliases.map((alias) => alias.trim().toLowerCase());
  return {
    id,
    name,
    latitude,
    longitude,
    aliases: Array.from(
      new Set([
        name.trim().toLowerCase(),
        id.replace(/-/g, ' '),
        ...normalizedAliases,
      ]),
    ),
  };
}

